// Reproduce the Unicode casing used by the local Zod baseline on Node 24.15.0.
// ECMAScript Default Case Conversion uses Unicode Default Case Conversion;
// single-code-point inputs include all unconditional SpecialCasing expansions.
// The only language-neutral contextual rule, Final_Sigma, is applied at runtime.
// Locale-dependent Lithuanian/Turkish/Azeri rules do not apply to toLowerCase.
// Regenerate: node scripts/generate_unicode_case.mjs
// Verify tables and all scalars/context on Wasm and JS in a temporary checkout:
// node scripts/generate_unicode_case.mjs --verify
// Emit only the independent oracle fixture: --write-oracle <file.mbt>
import { cpSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

if (process.version !== "v24.15.0" || process.versions.unicode !== "17.0") {
  throw new Error("Generation requires Node v24.15.0 with Unicode 17.0 data");
}

const output = new URL("../core/unicode_case_data.mbt", import.meta.url);
const cased = /\p{Cased}/u;
const ignorable = /\p{Case_Ignorable}/u;
const single = { lower: [], upper: [] };
const expansions = { lower: [], upper: [] };
const properties = { cased: [], ignorable: [] };
const oracleCases = [];
const sigmaCases = [];
const verify = process.argv.includes("--verify");
const oracleArgument = process.argv.indexOf("--write-oracle");
const writeOracle = verify || oracleArgument >= 0;
if (oracleArgument >= 0 && !process.argv[oracleArgument + 1]) {
  throw new Error("--write-oracle requires an output file path");
}

for (let point = 0; point <= 0x10ffff; point++) {
  if (point >= 0xd800 && point <= 0xdfff) continue;
  const source = String.fromCodePoint(point);
  const isCased = cased.test(source);
  const isIgnorable = ignorable.test(source);
  if (isCased) properties.cased.push(point);
  if (isIgnorable) properties.ignorable.push(point);
  if (writeOracle) {
    const lower = source.toLowerCase();
    const upper = source.toUpperCase();
    if (source !== lower || source !== upper) oracleCases.push([point, lower, upper]);
    if (isCased || isIgnorable) {
      for (const input of ["AΣ" + source, source + "Σ", "AΣ" + source + "A", "A" + source + "Σ"]) {
        sigmaCases.push([input, input.toLowerCase()]);
      }
    }
  }
  for (const kind of ["lower", "upper"]) {
    const mapped = kind === "lower" ? source.toLowerCase() : source.toUpperCase();
    if (mapped === source) continue;
    const points = [...mapped];
    if (points.length === 1) single[kind].push([point, mapped.codePointAt(0) - point]);
    else expansions[kind].push([point, mapped]);
  }
}

function mappingRanges(entries) {
  const result = [];
  for (let i = 0; i < entries.length;) {
    const [start, delta] = entries[i];
    let end = start;
    const next = entries[i + 1];
    const step = next && next[1] === delta && next[0] - start <= 2 ? next[0] - start : 1;
    let j = i + 1;
    while (j < entries.length && entries[j][1] === delta && entries[j][0] === end + step) {
      end = entries[j][0];
      j++;
    }
    result.push([start, end, step, delta]);
    i = j;
  }
  return result;
}

function propertyRanges(points) {
  const result = [];
  for (const point of points) {
    const previous = result.at(-1);
    if (previous && previous[1] + 1 === point) previous[1] = point;
    else result.push([point, point]);
  }
  return result;
}

function numericTable(name, rows, type) {
  return `///|\nlet ${name} : Array[${type}] = [\n${rows.map(row => `  (${row.join(", ")}),`).join("\n")}\n]\n`;
}

function expansionTable(name, entries) {
  const rows = entries.map(([point, mapped]) => {
    const escaped = [...mapped].map(char => `\\u{${char.codePointAt(0).toString(16)}}`).join("");
    return `  (${point}, "${escaped}"),`;
  });
  if (rows.length === 1) {
    return `///|\nlet ${name} : Array[(Int32, String)] = [${rows[0].trim().slice(0, -1)}]\n`;
  }
  return `///|\nlet ${name} : Array[(Int32, String)] = [\n${rows.join("\n")}\n]\n`;
}

let generated = `// Generated by scripts/generate_unicode_case.mjs; do not edit.\n// Unicode 17.0 via Node v24.15.0, ICU ${process.versions.icu}, V8 ${process.versions.v8}.\n// Sources: ECMAScript String.prototype.toLowerCase/toUpperCase and\n// Unicode Cased/Case_Ignorable property escapes in that pinned runtime.\n// Ranges contain (first, last, stride, delta); other entries are identity.\n\n`;
for (const kind of ["lower", "upper"]) {
  generated += numericTable(`unicode_${kind}_ranges`, mappingRanges(single[kind]), "(Int32, Int32, Int32, Int32)") + "\n";
  generated += expansionTable(`unicode_${kind}_expansions`, expansions[kind]) + "\n";
}
for (const kind of ["cased", "ignorable"]) {
  generated += numericTable(`unicode_${kind}_ranges`, propertyRanges(properties[kind]), "(Int32, Int32)") + "\n";
}
generated = generated.trimEnd() + "\n";
if (process.argv.includes("--check") || verify) {
  if (readFileSync(output, "utf8").replace(/\r\n/g, "\n") !== generated) {
    throw new Error("Unicode tables are stale; regenerate them");
  }
  console.log("Unicode 17.0 tables match the pinned Node runtime");
} else if (oracleArgument < 0) {
  writeFileSync(output, generated);
  console.log(`Generated ${Buffer.byteLength(generated)} bytes of Unicode 17.0 tables`);
}

function moonString(value) {
  return '"' + [...value].map(char => `\\u{${char.codePointAt(0).toString(16)}}`).join("") + '"';
}

function oracleFixture() {
  let source = `// Independent Node Unicode 17.0 oracle; generated, not a production-table lookup.
///|
test "Unicode default casing matches Node for every Unicode scalar" {
  let changed : Array[(Int, String, String)] = [
${oracleCases.map(([point, lower, upper]) => `    (${point}, ${moonString(lower)}, ${moonString(upper)}),`).join("\n")}
  ]
  let mut cursor = 0
  for point in 0..<0x110000 {
    if point >= 0xd800 && point <= 0xdfff { continue }
    let input = point.unsafe_to_char().to_string()
    let (lower, upper) = if cursor < changed.length() && changed[cursor].0 == point {
      let (_, lower, upper) = changed[cursor]
      cursor = cursor + 1
      (lower, upper)
    } else { (input, input) }
    assert_eq(ecma_case_convert(input, false), lower)
    assert_eq(ecma_case_convert(input, true), upper)
  }
}
`;
  // Separate test functions stay below WebAssembly's per-function local limit.
  for (let offset = 0; offset < sigmaCases.length; offset += 2000) {
    const chunk = sigmaCases.slice(offset, offset + 2000);
    source += `
///|
test "Final Sigma oracle cases ${offset}-${offset + chunk.length}" {
  let cases : Array[(String, String)] = [
${chunk.map(([input, expected]) => `    (${moonString(input)}, ${moonString(expected)}),`).join("\n")}
  ]
  for (input, expected) in cases {
    assert_eq(ecma_case_convert(input, false), expected)
  }
}
`;
  }
  return source;
}

if (oracleArgument >= 0) {
  const oracleOutput = process.argv[oracleArgument + 1];
  writeFileSync(oracleOutput, oracleFixture());
  console.log(`Wrote oracle to ${oracleOutput}: 1,112,064 scalars and ${sigmaCases.length} sigma contexts`);
}

if (verify) {
  const root = fileURLToPath(new URL("../", import.meta.url));
  const scratch = mkdtempSync(join(tmpdir(), "moon-zod-unicode-"));
  try {
    const scratchCore = join(scratch, "core");
    mkdirSync(scratchCore);
    cpSync(join(root, "moon.mod"), join(scratch, "moon.mod"));
    cpSync(join(root, ".mooncakes"), join(scratch, ".mooncakes"), { recursive: true });
    cpSync(join(root, "core/moon.pkg"), join(scratchCore, "moon.pkg"));
    for (const file of readdirSync(join(root, "core"))) {
      if (file.endsWith(".mbt") && !file.endsWith("_test.mbt") && !file.endsWith("_wbtest.mbt")) {
        cpSync(join(root, "core", file), join(scratchCore, file));
      }
    }
    const fixture = join(scratchCore, "unicode_oracle_wbtest.mbt");
    writeFileSync(fixture, oracleFixture());
    console.log(`Oracle checkout: ${scratch}`);
    console.log(`Comparing 1,112,064 scalars in both directions and ${sigmaCases.length} sigma contexts`);
    for (const target of ["wasm", "js"]) {
      const result = spawnSync("moon", ["test", "core/unicode_oracle_wbtest.mbt", "--frozen", "--target", target], {
        cwd: scratch,
        stdio: "inherit",
        shell: false,
      });
      if (result.error) throw result.error;
      if (result.status !== 0) throw new Error(`Unicode oracle failed on ${target}`);
    }
  } finally {
    if (process.argv.includes("--keep-oracle")) {
      console.log(`Kept oracle checkout: ${scratch}`);
    } else {
      const resolvedScratch = realpathSync(scratch);
      const resolvedTemp = realpathSync(tmpdir());
      if (dirname(resolvedScratch) !== resolvedTemp || !basename(resolvedScratch).startsWith("moon-zod-unicode-")) {
        throw new Error(`Refusing to remove an unexpected oracle path: ${resolvedScratch}`);
      }
      rmSync(resolvedScratch, { recursive: true, force: true });
    }
  }
}
